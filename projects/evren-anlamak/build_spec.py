def rule_ca(n=30, w=8, gens=16):
    c = [0] * w; c[w // 2] = 1; rows = []
    for _ in range(gens):
        rows.append(c[:]); c = [(n >> (c[(i - 1) % w] * 4 + c[i] * 2 + c[(i + 1) % w])) & 1 for i in range(w)]
    return rows
