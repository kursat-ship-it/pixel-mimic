def norm(text):
    for k, v in ALIASES.items():
        if k != "x": text = text.replace(k, v)
    return text


def missing(text):
    return sorted({c for c in norm(text) if c not in GLYPHS and c not in "\n*"})


def line_bitmap(segs):
    """segs = [(text, highlight)] → (10×W bool mask, 10×W bool highlight-mask) in dots."""
    cols, hcols = [], []
    for s, hi in segs:
        for ch in norm(s):
            g = GLYPHS.get(ch, GLYPHS["?"])
            cols.append(g); hcols.append(np.full(g.shape, hi))
            cols.append(np.zeros((10, 1), bool)); hcols.append(np.zeros((10, 1), bool))
    if not cols: return np.zeros((10, 1), bool), np.zeros((10, 1), bool)
    return np.concatenate(cols[:-1], 1), np.concatenate(hcols[:-1], 1)


def text_mask(text):
    """Multi-line centred mask at 1 dot per pixel (for in-world etched text)."""
    lines = [line_bitmap([(l, False)])[0] for l in text.split("\n")]
    w = max(l.shape[1] for l in lines); out = np.zeros((10 * len(lines), w + 2), bool)
    for i, l in enumerate(lines):
        x = (w + 2 - l.shape[1]) // 2; out[i * 10:i * 10 + 10, x:x + l.shape[1]] = l
    return out


